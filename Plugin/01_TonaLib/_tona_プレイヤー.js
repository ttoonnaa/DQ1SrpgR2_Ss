var tona_UnitControl = {
	__dummy: null

	// *****************************************************************************************************************************
	// プレイヤーIDを取得する
	// -----------------------------------------------------------------------------------------------------------------------------

	, getPlayerId: function(unit) {

		// プレイヤーだと分かっているユニットからプレイヤーIDを取得する
		// プレイヤーをエネミーや同盟軍として登場させた場合、getId() では取得できない

		// 正しくプレイヤーの場合
		if (unit.getId() < 65536) {
			return unit.getId();
		}
		// プレイヤーをインポートした場合
		else if (unit.getImportSrcId() >= 0) {
			return unit.getImportSrcId();
		}

		return -1;
	}

	// *****************************************************************************************************************************
	// 内部レベルを取得する
	// -----------------------------------------------------------------------------------------------------------------------------

	, getInnerLevel: function(unit) {

		return unit.getLv();
	}
};

